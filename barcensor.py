"""
BarCensor - ComfyUI custom node
===============================

Censor a region with solid COLOR BARS instead of mosaic.

Geometry contract (the important part):
    Bar #1 defines the direction of the whole group.
    Every other bar is generated by translating bar #1 along its own normal,
    so ALL bars are parallel to bar #1 by construction - they can never
    drift into different angles.

    Angle sources:
        auto_rect : fit a MINIMUM AREA RECTANGLE to the mask, measure how far
                    its long side is rotated from 0 deg, and run the bars
                    along that direction. This is the "relative angle of the
                    region" and is the recommended default.
        auto_pca  : principal axis (covariance eigenvector) of the mask.
        manual    : user supplied degrees (0 = horizontal, 90 = vertical).

    Bar orientation relative to that axis (bar_orientation):
        along_axis       : bars RUN along the main axis (default)
        across_axis      : bars run ACROSS it (+90 deg). Use this when the
                           region is tall and you still want horizontal bars.
        axis_plus_offset : main axis + axis_offset degrees

    Thickness:
        auto   : thickness = period * thickness_ratio, where
                 period = (block height) / bar_count
                 -> the bar set stays proportional no matter how many bars
                    you ask for; changing bar_count re-scales the bars.
        manual : fixed px, only clamped by period * thickness_ratio.

    Default shape is a ROTATED RECTANGLE: straight edges, sharp corners.
    The mask only decides WHERE the bar block sits (position, angle, size),
    it does NOT cut the bar into the mask silhouette. Use
    bar_shape = "conform_mask" if you want the bars to follow the outline.
"""

import math

import numpy as np
import torch

try:
    import cv2

    _HAS_CV2 = True
except Exception:  # pragma: no cover - cv2 is always present in ComfyUI
    cv2 = None
    _HAS_CV2 = False


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------
def _parse_color(preset: str, hex_str: str):
    """Return an (r, g, b) tuple in 0..1."""
    if preset == "black":
        return (0.0, 0.0, 0.0)
    if preset == "white":
        return (1.0, 1.0, 1.0)
    if preset == "gray":
        return (0.5, 0.5, 0.5)

    s = (hex_str or "").strip().lstrip("#")
    if len(s) == 3:
        s = "".join(ch * 2 for ch in s)
    try:
        r = int(s[0:2], 16) / 255.0
        g = int(s[2:4], 16) / 255.0
        b = int(s[4:6], 16) / 255.0
        return (r, g, b)
    except Exception:
        return (0.0, 0.0, 0.0)


def _region_from_mask(mask, h, w, invert=False):
    """mask (torch [H,W] or None) -> float32 region array [H,W] in 0..1."""
    if mask is None:
        return np.ones((h, w), dtype=np.float32)

    m = mask.detach().cpu().numpy()
    while m.ndim > 2:
        m = m[0]
    m = m.astype(np.float32)
    if m.shape != (h, w):
        if _HAS_CV2:
            m = cv2.resize(m, (w, h), interpolation=cv2.INTER_LINEAR)
        else:
            m = np.ones((h, w), dtype=np.float32)
    region = np.clip(m, 0.0, 1.0)
    if invert:
        region = 1.0 - region
    return region


def _pca_angle(region):
    """Principal axis of the mask, in degrees."""
    ys, xs = np.nonzero(region > 0.5)
    if xs.size < 2:
        return 0.0
    pts = np.stack([xs.astype(np.float64), ys.astype(np.float64)], axis=1)
    pts = pts - pts.mean(axis=0)
    cov = (pts.T @ pts) / max(1, pts.shape[0] - 1)
    vals, vecs = np.linalg.eigh(cov)
    vec = vecs[:, int(np.argmax(vals))]
    return math.degrees(math.atan2(vec[1], vec[0]))


def _min_area_rect_angle(region):
    """
    Fit a minimum area rectangle to the mask and return the rotation of its
    LONG side relative to 0 deg, normalised to [-90, 90).

    Works directly on the rectangle corner points (cv2.boxPoints) so it does
    not depend on which OpenCV minAreaRect angle convention is in play.
    """
    if not _HAS_CV2:
        return _pca_angle(region)

    binary = (region > 0.5).astype(np.uint8)
    contours, _ = cv2.findContours(binary, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        return 0.0

    cnt = max(contours, key=cv2.contourArea)
    if cv2.contourArea(cnt) <= 0 or len(cnt) < 3:
        return _pca_angle(region)

    box = cv2.boxPoints(cv2.minAreaRect(cnt)).astype(np.float64)

    best_vec, best_len = None, -1.0
    for i in range(4):
        d = box[(i + 1) % 4] - box[i]
        l = float(d[0] * d[0] + d[1] * d[1])
        if l > best_len:
            best_len, best_vec = l, d
    if best_vec is None or best_len <= 0.0:
        return _pca_angle(region)

    ang = math.degrees(math.atan2(best_vec[1], best_vec[0]))
    # the bar direction is symmetric over 180 deg -> fold into [-90, 90)
    return ((ang + 90.0) % 180.0) - 90.0


def _resolve_angle(region, mode: str, manual_deg: float):
    """Angle of bar #1 in degrees. 0 = horizontal, 90 = vertical."""
    if mode == "horizontal":
        return 0.0, "horizontal"
    if mode == "vertical":
        return 90.0, "vertical"
    if mode == "diagonal_down":
        return 45.0, "diagonal_down"
    if mode == "diagonal_up":
        return -45.0, "diagonal_up"
    if mode == "manual":
        return float(manual_deg), "manual"
    if mode == "auto_pca":
        return _pca_angle(region), "auto_pca"
    # default: minimum area rectangle
    return _min_area_rect_angle(region), "auto_rect"


def _normalize_angle(deg):
    """Fold an angle into [-90, 90) - a bar direction is symmetric over 180."""
    return ((float(deg) + 90.0) % 180.0) - 90.0


def _apply_orientation(base_deg, orientation, offset_deg):
    """Turn the region's main axis into the actual bar direction."""
    if orientation == "across_axis":
        return _normalize_angle(base_deg + 90.0)
    if orientation == "axis_plus_offset":
        return _normalize_angle(base_deg + float(offset_deg))
    return _normalize_angle(base_deg)


def _rotated_frame(h, w, cx, cy, angle_deg):
    """Return per-pixel U (along the bar) and V (normal to the bar) grids."""
    a = math.radians(float(angle_deg))
    ca, sa = math.cos(a), math.sin(a)
    X = np.arange(w, dtype=np.float32)[None, :]   # column index
    Y = np.arange(h, dtype=np.float32)[:, None]   # row index
    U = (X - cx) * ca + (Y - cy) * sa
    V = -(X - cx) * sa + (Y - cy) * ca
    return U, V


def build_bar_mask(region, angle_deg, bar_count, thickness_px,
                   shape="rectangle", length_mode="fit_region",
                   length_overflow=0, region_pad=0,
                   thickness_mode="auto", thickness_ratio=0.8):
    """
    Build the censor bar mask.

    region  : [H, W] float32, >0.5 marks the area to censor
    returns : ([H, W] float32 bar mask in 0..1, info dict)
    """
    h, w = region.shape
    info = {"thickness": 0.0, "period": 0.0, "block_w": 0.0, "block_h": 0.0}

    ys, xs = np.nonzero(region > 0.5)
    if xs.size == 0:
        return np.zeros((h, w), dtype=np.float32), info

    cx = float(xs.mean())
    cy = float(ys.mean())
    U, V = _rotated_frame(h, w, cx, cy, angle_deg)

    ru = U[ys, xs]
    rv = V[ys, xs]
    u0, u1 = float(ru.min()), float(ru.max())
    v0, v1 = float(rv.min()), float(rv.max())

    count = max(1, int(bar_count))
    ov = float(length_overflow)
    pad = float(region_pad)
    ratio = float(thickness_ratio)
    full = math.hypot(w, h)
    bars = np.zeros((h, w), dtype=np.float32)

    if shape == "conform_mask":
        # bars inherit the mask silhouette (organic, curved edges)
        if pad > 0 and _HAS_CV2:
            k = int(pad) * 2 + 1
            region = cv2.dilate(region, np.ones((k, k), dtype=np.uint8), iterations=1)
            ys, xs = np.nonzero(region > 0.5)
            if xs.size == 0:
                return bars, info
            ru = U[ys, xs]
            rv = V[ys, xs]
            u0, u1 = float(ru.min()), float(ru.max())
            v0, v1 = float(rv.min()), float(rv.max())

        extent = max(v1 - v0, 1.0)
        v_mid = 0.5 * (v0 + v1)
        u0 -= ov
        u1 += ov

        if count == 1:
            period, thick = extent, extent
        else:
            period = extent / count
            if thickness_mode == "auto":
                thick = max(period * ratio, 1.0)
            else:
                thick = max(min(float(thickness_px), period * ratio), 1.0)

        info.update({"thickness": thick, "period": period,
                     "block_w": u1 - u0, "block_h": extent})

        for k in range(count):
            vc = v_mid + (k - (count - 1) / 2.0) * period
            band = (V >= vc - thick / 2.0) & (V <= vc + thick / 2.0) & (region > 0.5)
            if not band.any():
                continue
            if length_mode == "full_image":
                bu0, bu1 = -full, full
            else:
                ub = U[band]
                bu0, bu1 = float(ub.min()) - ov, float(ub.max()) + ov
            bars[band & (U >= bu0) & (U <= bu1)] = 1.0
        return bars, info

    # ---- rectangle: straight edges, sharp corners -------------------------
    u0 -= (ov + pad)
    u1 += (ov + pad)
    v0 -= pad
    v1 += pad

    extent = max(v1 - v0, 1.0)
    v_mid = 0.5 * (v0 + v1)

    if count == 1:
        period, thick = extent, extent
    else:
        period = extent / count
        if thickness_mode == "auto":
            # thickness follows the bar count: period * ratio
            thick = max(period * ratio, 1.0)
        else:
            thick = max(min(float(thickness_px), period * ratio), 1.0)

    if length_mode == "full_image":
        u0, u1 = -full, full

    info.update({"thickness": thick, "period": period,
                 "block_w": u1 - u0, "block_h": extent})

    for k in range(count):
        vc = v_mid + (k - (count - 1) / 2.0) * period
        bars[(U >= u0) & (U <= u1) &
             (V >= vc - thick / 2.0) & (V <= vc + thick / 2.0)] = 1.0
    return bars, info


def _composite(img_np, bars, rgb, opacity, feather):
    m = bars.astype(np.float32)
    if feather > 0 and _HAS_CV2:
        k = int(feather) * 2 + 1
        m = cv2.GaussianBlur(m, (k, k), 0)
        m = np.clip(m, 0.0, 1.0)
    m = m * float(opacity)

    c = img_np.shape[-1]
    if c == 1:
        col = np.array([rgb[0]], dtype=np.float32)
    elif c >= 3:
        col = np.array(list(rgb) + [1.0] * (c - 3), dtype=np.float32)
    else:
        col = np.array(list(rgb)[:c], dtype=np.float32)

    out = img_np * (1.0 - m[..., None]) + col.reshape(1, 1, -1) * m[..., None]
    if c == 4:  # keep the original alpha
        out[..., 3] = img_np[..., 3]
    return np.clip(out, 0.0, 1.0), m


