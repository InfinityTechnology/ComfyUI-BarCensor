# node
# --------------------------------------------------------------------------
class BarCensor:
    """Censor a region with parallel solid-color bars (no mosaic)."""

    CATEGORY = "🧪AILab/▬BarCensor"
    RETURN_TYPES = ("IMAGE", "MASK", "STRING")
    RETURN_NAMES = ("image", "censor_mask", "info")
    FUNCTION = "apply_censor"

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "image": ("IMAGE",),
                "bar_count": ("INT", {"default": 1, "min": 1, "max": 32, "step": 1}),
                "angle_mode": (["auto_rect", "auto_pca", "horizontal", "vertical",
                                "diagonal_down", "diagonal_up", "manual"],),
                "angle": ("FLOAT", {"default": 0.0, "min": -180.0, "max": 180.0,
                                    "step": 0.5}),
                "bar_orientation": (["along_axis", "across_axis", "axis_plus_offset"],),
                "axis_offset": ("FLOAT", {"default": 0.0, "min": -180.0, "max": 180.0,
                                          "step": 0.5}),
                "bar_shape": (["rectangle", "conform_mask"],),
                "thickness_mode": (["auto", "manual"],),
                "thickness_ratio": ("FLOAT", {"default": 0.8, "min": 0.05, "max": 1.0,
                                              "step": 0.01}),
                "bar_thickness": ("INT", {"default": 24, "min": 1, "max": 1024, "step": 1}),
                "length_mode": (["fit_region", "full_image"],),
                "length_overflow": ("INT", {"default": 8, "min": 0, "max": 512, "step": 1}),
                "color": (["black", "white", "gray", "custom"],),
                "custom_color": ("STRING", {"default": "#000000"}),
                "opacity": ("FLOAT", {"default": 1.0, "min": 0.0, "max": 1.0,
                                      "step": 0.01}),
                "feather": ("INT", {"default": 1, "min": 0, "max": 32, "step": 1}),
            },
            "optional": {
                "mask": ("MASK",),
                "invert_mask": ("BOOLEAN", {"default": False}),
                "region_expand": ("INT", {"default": 4, "min": 0, "max": 256, "step": 1}),
            },
        }

    def apply_censor(self, image, bar_count, angle_mode, angle,
                     bar_orientation, axis_offset, bar_shape,
                     thickness_mode, thickness_ratio, bar_thickness,
                     length_mode, length_overflow, color, custom_color,
                     opacity, feather, mask=None, invert_mask=False,
                     region_expand=4):
        try:
            b, h, w, c = image.shape
            rgb = _parse_color(color, custom_color)

            out_imgs = []
            out_masks = []
            infos = []

            for i in range(b):
                img_np = image[i].detach().cpu().numpy().astype(np.float32)
                cur_mask = mask[i] if mask is not None else None

                region = _region_from_mask(cur_mask, h, w, invert_mask)
                axis, ang_src = _resolve_angle(region, angle_mode, angle)
                ang = _apply_orientation(axis, bar_orientation, axis_offset)
                bars, info = build_bar_mask(
                    region, ang, bar_count, bar_thickness,
                    bar_shape, length_mode, length_overflow,
                    region_expand, thickness_mode, thickness_ratio,
                )
                res, m = _composite(img_np, bars, rgb, opacity, feather)

                out_imgs.append(torch.from_numpy(res).float())
                out_masks.append(torch.from_numpy(m).float())
                infos.append(
                    "axis = {:.1f} deg [{}] + {} -> bar angle = {:.1f} deg  |  "
                    "bars = {}  |  block = {:.0f} x {:.0f} px  |  "
                    "period = {:.1f} px  |  thickness = {:.1f} px [{}]".format(
                        axis, ang_src, bar_orientation, ang,
                        max(1, int(bar_count)),
                        info["block_w"], info["block_h"], info["period"],
                        info["thickness"], thickness_mode,
                    )
                )

            return (torch.stack(out_imgs, dim=0), torch.stack(out_masks, dim=0),
                    "\n".join(infos))

        except Exception:
            # never break the graph - pass the image through untouched
            if mask is not None:
                return (image, mask, "BarCensor: failed, passthrough")
            zero = torch.zeros((image.shape[0], image.shape[1], image.shape[2]),
                               dtype=torch.float32)
            return (image, zero, "BarCensor: failed, passthrough")


